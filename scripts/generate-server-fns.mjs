#!/usr/bin/env node
/**
 * Generates the client-side facades and the server registry for every
 * `*.functions.ts` module.
 *
 * Run after adding/removing a server function:
 *   npm run generate:server-fns
 *
 * - Client facade: `src/lib/api-client/<name>.functions.ts`
 * - Server registry: `src/lib/server-fn/registry.server.ts`
 */
import { readdirSync, readFileSync, statSync, writeFileSync, mkdirSync } from "node:fs";
import { join, relative, basename, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const libDir = join(root, "src", "lib");
const outDir = join(root, "src", "lib", "api-client");

const IGNORED_DIRS = new Set(["api-client", "server-fn"]);

function walk(dir) {
  const entries = [];
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) {
      if (IGNORED_DIRS.has(entry)) continue;
      entries.push(...walk(full));
    } else if (entry.endsWith(".functions.ts")) {
      entries.push(full);
    }
  }
  return entries;
}

const modules = walk(libDir).sort();

/** @type {{ key: string, name: string, moduleRel: string, fileRel: string }[]} */
const functions = [];
/** @type {{ rel: string, alias: string, file: string }[]} */
const moduleImports = [];

for (const file of modules) {
  const rel = relative(libDir, file).replace(/\\/g, "/"); // api/obras.functions.ts
  const moduleRel = rel.replace(/\.ts$/, ""); // api/obras.functions
  const source = readFileSync(file, "utf8");
  const regex = /export\s+const\s+([A-Za-z0-9_]+)\s*=\s*createServerFn/g;
  let match;
  let count = 0;
  while ((match = regex.exec(source))) {
    functions.push({
      key: `${moduleRel}.${match[1]}`,
      name: match[1],
      moduleRel,
      fileRel: rel,
    });
    count += 1;
  }
  if (count > 0) {
    moduleImports.push({
      rel: moduleRel,
      alias: `m_${moduleRel.replace(/[^A-Za-z0-9_]/g, "_")}`,
      file,
    });
  }
}

mkdirSync(outDir, { recursive: true });

const byModule = new Map();
for (const fn of functions) {
  if (!byModule.has(fn.moduleRel)) byModule.set(fn.moduleRel, []);
  byModule.get(fn.moduleRel).push(fn);
}

const header = `// AUTO-GENERATED by scripts/generate-server-fns.mjs — do not edit by hand.\n// Run \`npm run generate:server-fns\` after adding or removing server functions.\n`;

for (const [moduleRel, fns] of byModule) {
  const name = basename(moduleRel); // obras.functions
  const outFile = join(outDir, `${name}.ts`);
  const body = [
    `"use client";`,
    ``,
    header,
    `import type * as Impl from "@/lib/${moduleRel}";`,
    `import { clientFn } from "@/lib/server-fn/client";`,
    ``,
    `export type * from "@/lib/${moduleRel}";`,
    ``,
    ...fns.map((fn) => `export const ${fn.name} = clientFn<typeof Impl.${fn.name}>("${fn.key}");`),
    ``,
  ].join("\n");
  writeFileSync(outFile, body, "utf8");
}

const registryLines = [
  `// AUTO-GENERATED by scripts/generate-server-fns.mjs — do not edit by hand.`,
  `// This module is only imported from the RPC route handler (server side).`,
  ``,
  ...moduleImports.map((m) => `import * as ${m.alias} from "@/lib/${m.rel}";`),
  ``,
  `export const registry: Record<string, { __execute: (input?: { data?: unknown }) => Promise<unknown> }> = {`,
  ...functions.map((fn) => {
    const alias = moduleImports.find((m) => m.rel === fn.moduleRel).alias;
    return `  "${fn.key}": ${alias}.${fn.name},`;
  }),
  `};`,
  ``,
];

writeFileSync(join(root, "src", "lib", "server-fn", "registry.server.ts"), registryLines.join("\n"), "utf8");

console.log(`Generated ${byModule.size} client facades and ${functions.length} registry entries.`);
